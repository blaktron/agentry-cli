func TestStage(t *testing.T) {
	in, out, dst := staged(t), t.TempDir(), t.TempDir()
	if err := os.WriteFile(filepath.Join(out, "report.pdf.txt"), []byte("report text\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	res := &Result{In: in, Out: out, Report: runnerdecode.Report{Schema: runnerdecode.Schema, Files: []runnerdecode.File{
		{Path: "blob.bin", Family: runnerdecode.FamilyUnknown, Outcome: runnerdecode.OutcomeUndecodable, Reason: "not text, and no decoder reads this kind of file"},
		{Path: "notes.md", Family: runnerdecode.FamilyText, Outcome: runnerdecode.OutcomeText},
		{Path: "report.pdf", Family: runnerdecode.FamilyPDF, Tool: "pdftotext", Outcome: runnerdecode.OutcomeDecoded, Output: "report.pdf.txt"},
	}}}
	docs, inputs, err := res.Stage(map[string]string{"report.pdf": "/given/Report.pdf"}, dst)
	if err != nil {
		t.Fatal(err)
	}
	if len(docs) != 3 {
		t.Fatalf("docs %+v", docs)
	}
	var names []string
	for _, p := range inputs {
		names = append(names, filepath.Base(p))
	}
	if strings.Join(names, ",") != "documents.json,notes.md,report.pdf.txt" {
		t.Fatalf("inputs %v", names)
	}
	if b, _ := os.ReadFile(filepath.Join(dst, "report.pdf.txt")); string(b) != "report text\n" {
		t.Fatalf("staged text %q", b)
	}
	raw, _ := os.ReadFile(filepath.Join(dst, DocumentsFile))
	want := `{
  "documents": [
    {
      "name": "blob.bin",
      "family": "unknown",
      "unread": "not text, and no decoder reads this kind of file"
    },
    {
      "name": "notes.md",
      "read": "notes.md",
      "family": "text"
    },
    {
      "name": "report.pdf",
      "givenAs": "/given/Report.pdf",
      "read": "report.pdf.txt",
      "family": "pdf",
      "decodedBy": "pdftotext"
    }
  ]
}
`
	if string(raw) != want {
		t.Fatalf("documents.json =\n%s", raw)
	}
	t.Run("a text document named as another's decoded text is refused", func(t *testing.T) {
		clash := &Result{In: in, Out: out, Report: runnerdecode.Report{Files: []runnerdecode.File{
			{Path: "report.pdf", Outcome: runnerdecode.OutcomeDecoded, Output: "report.pdf.txt"},
			{Path: "report.pdf.txt", Outcome: runnerdecode.OutcomeText},
		}}}
		if _, _, err := clash.Stage(nil, t.TempDir()); err == nil || !strings.Contains(err.Error(), "would both be read as report.pdf.txt") {
			t.Fatalf("err = %v", err)
		}
	})
	t.Run("a staged document that became a link is not copied", func(t *testing.T) {
		if err := os.Remove(filepath.Join(in, "notes.md")); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink("/etc/hostname", filepath.Join(in, "notes.md")); err != nil {
			t.Fatal(err)
		}
		if _, _, err := res.Stage(nil, t.TempDir()); err == nil || !strings.Contains(err.Error(), "not a regular file") {
			t.Fatalf("err = %v", err)
		}
	})
}

// TestAStagedDocumentTheReportLeavesOutIsNotDecoded: a decoder that drops a
// document from its report cannot make it vanish from what a run is told.
func TestAStagedDocumentTheReportLeavesOutIsNotDecoded(t *testing.T) {
	in := staged(t)
	f := &dockerx.Fake{Foreground: map[string]*dockerx.FakeForeground{"agentry-decode-": {Before: playDecode(t, []runnerdecode.File{
		{Path: "notes.md", Family: runnerdecode.FamilyText, Outcome: runnerdecode.OutcomeText},
	})}}}
	res, err := Run(context.Background(), f, sampleImage, in, t.TempDir(), policy.Limits{}.WithDefaults(), os.Stderr)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, file := range res.Report.Files {
		got[file.Path] = string(file.Outcome) + ": " + file.Reason
	}
	for _, p := range []string{"blob.bin", "deck.pptx", "link.pdf", "report.pdf"} {
		if got[p] != "undecodable: the decode's report does not name it" {
			t.Errorf("%s: %q", p, got[p])
		}
	}
	if got["notes.md"] != "text: " {
		t.Errorf("notes.md: %q", got["notes.md"])
	}
}

// callsOf is the arguments of every call of op the fake recorded, in order.
func callsOf(f *dockerx.Fake, op string) []string {
	var args []string
	for _, c := range f.Calls {
		if c.Op == op {
			args = append(args, c.Arg)
		}
	}
	return args
}

// TestRunHoldsAnArchivesMembersToIt: a report of an archive and its
// members passes the checks, the members' texts are read through them,
// and the run is told each member's fixed reason.
func TestRunHoldsAnArchivesMembersToIt(t *testing.T) {
	in := staged(t)
	files := []runnerdecode.File{
		{Path: "blob.bin", Family: runnerdecode.FamilyArchive, Tool: "agentry-runner", Outcome: runnerdecode.OutcomeUnpacked, Why: runnerdecode.WhyTooLarge},
		{Path: "blob.bin/dir/a.md", Family: runnerdecode.FamilyText, Outcome: runnerdecode.OutcomeText, Output: "blob.bin/dir/a.md.txt", In: "blob.bin", Size: 6},
		{Path: "blob.bin/inner.tar", Family: runnerdecode.FamilyArchive, Tool: "agentry-runner", Outcome: runnerdecode.OutcomeUnpacked, In: "blob.bin"},
		{Path: "blob.bin/inner.tar/memo.docx", Family: runnerdecode.FamilyDocument, Tool: "pandoc", Outcome: runnerdecode.OutcomeDecoded, Output: "blob.bin/inner.tar/memo.docx.txt", In: "blob.bin/inner.tar"},
		{Path: "blob.bin/link", Family: runnerdecode.FamilyUnknown, Outcome: runnerdecode.OutcomeRefused, In: "blob.bin", Why: runnerdecode.WhyLink},
		{Path: "blob.bin/secret.md", Family: runnerdecode.FamilyUnknown, Outcome: runnerdecode.OutcomeUndecodable, In: "blob.bin", Why: runnerdecode.WhyEncrypted},
		{Path: "deck.pptx", Family: "presentation", Tool: "agentry-runner", Outcome: runnerdecode.OutcomeDecoded, Output: "deck.pptx.txt"},
		{Path: "link.pdf", Family: "unknown", Outcome: runnerdecode.OutcomeRefused},
		{Path: "notes.md", Family: "text", Outcome: runnerdecode.OutcomeText},
		{Path: "report.pdf", Family: "pdf", Tool: "pdftotext", Outcome: runnerdecode.OutcomeDecoded, Output: "report.pdf.txt"},
	}
	f := &dockerx.Fake{Foreground: map[string]*dockerx.FakeForeground{"agentry-decode-": {Before: playDecode(t, files)}}}
	res, err := Run(context.Background(), f, sampleImage, in, t.TempDir(), policy.Limits{}.WithDefaults(), os.Stderr)
	if err != nil {
		t.Fatal(err)
	}
	dst := filepath.Join(t.TempDir(), "a.md")
	if err := res.CopyText("blob.bin/dir/a.md", dst); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(dst); string(b) != "text of blob.bin/dir/a.md\n" {
		t.Fatalf("member text %q", b)
	}
	byPath := map[string]runnerdecode.File{}
	for _, file := range res.Report.Files {
		byPath[file.Path] = file
	}
	if got := UnreadReason(byPath["blob.bin/secret.md"]); got != "encrypted" {
		t.Errorf("encrypted member: %q", got)
	}
	if got := UnreadReason(byPath["blob.bin/link"]); got != "a link in an archive is never unpacked" {
		t.Errorf("link member: %q", got)
	}
	if got := UnpackedInPart(byPath["blob.bin"]); got != "unpacking stopped at the cap on unpacked bytes" {
		t.Errorf("partial archive: %q", got)
	}
	if got := UnpackedInPart(byPath["blob.bin/inner.tar"]); got != "" {
		t.Errorf("whole archive: %q", got)
	}
	if got, want := res.Counts(), "3 decoded, 2 read as text, 2 archives unpacked (1 in part), 3 not decoded (blob.bin/link, blob.bin/secret.md, link.pdf)"; got != want {
		t.Errorf("counts %q, want %q", got, want)
	}
	// The built-ins keep each document as given, so their layout lists
	// the archive as unread and leaves its members out (agentry-cli#619).
	docs, _, err := res.Stage(nil, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, d := range docs {
		names = append(names, d.Name)
		if d.Name == "blob.bin" && (d.Unread != archiveNotRead || d.Read != "") {
			t.Errorf("archive document %+v", d)
		}
	}
	if strings.Join(names, ",") != "blob.bin,deck.pptx,link.pdf,notes.md,report.pdf" {
		t.Errorf("documents %v", names)
	}
	if got := strings.Join(Skipped(docs), ","); got != "blob.bin,link.pdf" {
		t.Errorf("skipped %q", got)
	}
	for _, f := range res.Readable() {
		if f.In != "" {
			t.Errorf("a member is readable to a built-in: %+v", f)
		}
	}
}
