func TestEnsurePullsTheFilesImageByDigestAndBuildsOnce(t *testing.T) {
	ctx := context.Background()
	s := ImageSpec("agentry-runner:abc", testFiles)
	f := &dockerx.Fake{ImageFiles: map[string]string{s.Tag + ":" + FilesPackagesFile: "tesseract-ocr-5.5.0-r2\npandoc-cli-3.6.4-r0\n"}}
	ctxDir := t.TempDir()
	img, err := Ensure(ctx, f, "agentry-runner:abc", ensurePolicy(), ctxDir, os.Stderr)
	if err != nil {
		t.Fatal(err)
	}
	if img.Tag != s.Tag || img.Files != testFiles || strings.Join(img.Packages, ",") != "pandoc-cli-3.6.4-r0,tesseract-ocr-5.5.0-r2" {
		t.Fatalf("image %+v", img)
	}
	if got := callsOf(f, "Pull"); !slices.Equal(got, []string{testFiles}) {
		t.Fatalf("pulls %v, want the files image by digest once", got)
	}
	builds := callsOf(f, "Build")
	if len(builds) != 1 || !strings.HasPrefix(builds[0], s.Tag+"<-") {
		t.Fatalf("builds %v", builds)
	}
	b, err := os.ReadFile(filepath.Join(strings.TrimPrefix(builds[0], s.Tag+"<-"), "Dockerfile"))
	if err != nil || string(b) != s.Dockerfile() {
		t.Fatalf("the context's Dockerfile %q (%v)", b, err)
	}

	// Built already: nothing is pulled or built again.
	f2 := &dockerx.Fake{ExistingImages: map[string]bool{s.Tag: true}, ImageFiles: f.ImageFiles}
	if _, err := Ensure(ctx, f2, "agentry-runner:abc", ensurePolicy(), ctxDir, os.Stderr); err != nil {
		t.Fatal(err)
	}
	if len(callsOf(f2, "Pull")) != 0 || len(callsOf(f2, "Build")) != 0 {
		t.Fatalf("a built decode image was pulled or built again: %v", f2.Calls)
	}
}

