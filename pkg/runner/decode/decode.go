// Tool is one external decoder: the command the decode image keeps. The
// files image provides it (agentry-dockerimages build/agentry-files, whose
// Dockerfile names the Alpine packages); this CLI pins that image by digest.
type Tool struct {
	Command string
}

// Catalogue is every external decoder, named once for every caller. It is
// the application's, not the operator's exec catalogue: a decode step is
// the runner's own, like its proxy, and runs no command a QuickAgent
// declared. The decode image is minimized to exactly these and the runner.
var Catalogue = []Tool{
	{Command: "pandoc"},
	{Command: "pdftotext"},
	{Command: "tesseract"},
	{Command: "java"},
	{Command: "file"},
	{Command: "bsdtar"},
	{Command: "bsdcat"},
	{Command: "clamscan"},
}

// FilesPackagesFile is where the files image records the version apk
// resolved for each of its packages, one name-version a line.
const FilesPackagesFile = "/etc/agentry/files/packages"

// Spec is the decode image this machine builds: the files image, pinned by
// digest and pulled, with this CLI's runner binary copied in and the result
// minimized to the decoders and the runner. The build installs nothing
// (the base is pulled first, by digest, and the runner image is local), so
// it cannot fail as a run-time `apk add` did (agentry-cli#559; plan file-handling.md §1.1).
type Spec struct {
	// Tag is the local tag, which moves with the whole build.
	Tag string
	// Files is the files image, name:tag@sha256:digest.
	Files string
	// Runner is the local runner image whose binary is copied in.
	Runner string
}

// ImageSpec is the decode image for this runner image and files image.
// The tag is a hash of the whole build, so a new runner image, a new files
// image or a new recipe in a later CLI each get an image of their own and
// never reuse a stale one.
func ImageSpec(runnerImage, filesImage string) Spec {
	s := Spec{Files: filesImage, Runner: runnerImage}
	sum := sha256.Sum256([]byte(s.Dockerfile()))
	s.Tag = "agentry-decode:" + hex.EncodeToString(sum[:])[:16]
	return s
}

// Dockerfile is the decode image's build: the files image, the runner
// binary, and the minimize step, each in exec form. The files image has no
// entrypoint, so the runner is named as this one's: a decode container's
// argv is the runner's (`decode --in /in --out /out`).
func (s Spec) Dockerfile() string {
	quoted := make([]string, 0, len(Catalogue))
	for _, t := range Catalogue {
		quoted = append(quoted, strconv.Quote(t.Command))
	}
	sort.Strings(quoted)
	return "# generated by agentry: the decode image, the files image pinned by digest with this CLI's runner binary, minimized to the decoders (agentry-cli#559)\n" +
		"FROM " + s.Files + "\n" +
		"COPY --from=" + s.Runner + " /usr/local/bin/agentry-runner /usr/local/bin/agentry-runner\n" +
		"RUN [\"/usr/local/bin/agentry-runner\", \"minimize\", " + strings.Join(quoted, ", ") + "]\n" +
		"ENTRYPOINT [\"/usr/local/bin/agentry-runner\"]\n"
}

// Image is a built decode image, the files image it was built on, and the
// package versions that image recorded.
type Image struct {
	Tag      string
	Files    string
	Packages []string
	// Signatures is the ClamAV bundle Run mounts for the malware check
	// (clamdb.Ensure); none, every file is reported unchecked.
	Signatures clamdb.DB
}

// pullAttempts and pullBackoff bound the files image's pull: a registry
// that fails a pull now and then is retried, and one that keeps failing is
// named in the error rather than left as a bare exit class.
var (
	pullAttempts = 3
	pullBackoff  = 5 * time.Second
)

// Ensure builds the decode image when it is missing: it pulls the files
// image the policy names, by digest, then builds the offline layer on it,
// and reads back the versions the files image recorded.
func Ensure(ctx context.Context, d dockerx.Client, runnerImage string, pol *policy.Policy, ctxDir string, logw io.Writer) (Image, error) {
	files, err := filesRef(pol)
	if err != nil {
		return Image{}, err
	}
	s := ImageSpec(runnerImage, files)
	ok, err := d.ImageExists(ctx, s.Tag)
	if err != nil {
		return Image{}, err
	}
	if !ok {
		if err := pullFiles(ctx, d, files, logw); err != nil {
			return Image{}, err
		}
		dir := filepath.Join(ctxDir, "decode-"+s.Tag[strings.LastIndex(s.Tag, ":")+1:])
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return Image{}, fmt.Errorf("the decode image's context: %w", err)
		}
		if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(s.Dockerfile()), 0o600); err != nil {
			return Image{}, fmt.Errorf("the decode image's context: %w", err)
		}
		_, _ = fmt.Fprintf(logw, "building %s (the files image %s with this CLI's runner, minimized; nothing is installed)\n", s.Tag, files)
		if err := d.Build(ctx, dir, s.Tag, nil); err != nil {
			return Image{}, fmt.Errorf("build the decode image %s on %s: %w", s.Tag, files, err)
		}
	}
	b, err := d.ImageFile(ctx, s.Tag, FilesPackagesFile)
	if err != nil {
		return Image{}, fmt.Errorf("read the files image's package record: %w", err)
	}
	var pkgs []string
	for _, line := range strings.Split(string(b), "\n") {
		if line = strings.TrimSpace(line); line != "" {
			pkgs = append(pkgs, line)
		}
	}
	sort.Strings(pkgs)
	return Image{Tag: s.Tag, Files: files, Packages: pkgs}, nil
}

// PullFiles pulls the files image the policy names, by digest, unless it is
// here, and answers its reference: Ensure's pull alone, which a sandbox host
// runs before any run (`agentry files ensure`, agentry-cli#572), so the
// first run with inputs after an update does not download it.
func PullFiles(ctx context.Context, d dockerx.Client, pol *policy.Policy, logw io.Writer) (string, error) {
	files, err := filesRef(pol)
	if err != nil {
		return "", err
	}
	return files, pullFiles(ctx, d, files, logw)
}

// filesRef is the files image the policy names, refused unless it is pinned
// by digest.
func filesRef(pol *policy.Policy) (string, error) {
	files := pol.Images.FilesImage()
	if !policy.PinnedByDigest(files) {
		return "", fmt.Errorf("the files image %q is not pinned by digest; images.files must be <name>@sha256:<digest>", files)
	}
	return files, nil
}

// pullFiles pulls the files image unless it is here, retrying a failed
// pull, and says what failed and what it is for when every attempt does.
func pullFiles(ctx context.Context, d dockerx.Client, ref string, logw io.Writer) error {
	ok, err := d.ImageExists(ctx, ref)
	if err != nil || ok {
		return err
	}
	_, _ = fmt.Fprintf(logw, "pulling the files image %s (once on this machine)\n", ref)
	var last error
	for i := 1; i <= pullAttempts; i++ {
		if last = d.Pull(ctx, ref); last == nil {
			return nil
		}
		if i < pullAttempts {
			_, _ = fmt.Fprintf(logw, "pull failed (%v); trying again\n", last)
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(pullBackoff * time.Duration(i)):
			}
		}
	}
	return fmt.Errorf("could not pull the files image %s, which turns the run's documents into text, after %d attempts: %w", ref, pullAttempts, last)
}

// Result is one decode: the report the container wrote, checked, and the
// image that wrote it. Its files are read only through its own methods,
// which hold every read to the two directories.
type Result struct {
	Report runnerdecode.Report
	Image  Image
	// In holds the documents as given, each at its File.Path; Out the
	// texts, each at its File.Output.
	In, Out string
}

// The bounds on what the host reads back from the decode container.
const (
	// MaxTextBytes is the most of one decoded text the host reads: the
	// decoder's own cut, a whole knowledge pack.
	MaxTextBytes = 10 << 20
	// maxReportBytes bounds decode.json.
	maxReportBytes = 4 << 20
	// Timeout ends a whole decode.
	Timeout = 30 * time.Minute
)

// Run decodes every file under in into out. Both must be directories the
// caller made for this decode — they are relabelled for the container on a
// daemon with SELinux, which is a write to the host's labels and so never
// done to a directory a person owns — and in should hold copies of the
// documents, not the originals.
func Run(ctx context.Context, d dockerx.Client, img Image, in, out string, lim policy.Limits, stderr io.Writer) (*Result, error) {
	suffix := make([]byte, 4)
	if _, err := rand.Read(suffix); err != nil {
		return nil, err
	}
	name := "agentry-decode-" + hex.EncodeToString(suffix)
	argv := []string{"decode", "--in", "/in", "--out", "/out", "--unpack", "/unpack"}
	mounts := []dockerx.Mount{
		{Source: in, Target: "/in", ReadOnly: true, Relabel: true},
		{Source: out, Target: "/out", Relabel: true},
	}
	// The signatures are the runner home's own bundle, read-only, shared
	// by every decode on the machine (Relabel is docker's shared :z).
	if dir := img.Signatures.Dir; dir != "" {
		argv = append(argv, "--clamav", clamMount)
		mounts = append(mounts, dockerx.Mount{Source: dir, Target: clamMount, ReadOnly: true, Relabel: true})
	}
	r := dockerx.RunSpec{
		Name:    name,
		Image:   img.Tag,
		Argv:    argv,
		Network: "none",
		// Resolvable from /etc/hosts with no network: Tika looks its host
		// up at start, and an unresolvable name cost every call a DNS
		// timeout (agentry-cli#618).
		Hostname: "localhost",
		Mounts:   mounts,
		// The texts belong to the person who ran the command, and a
		// decoder runs with no more than they have.
		User:       invokingUser(),
		AutoRemove: true,
		Labels:     map[string]string{"agentry.decode": "1"},
	}.WithPosture(lim.Memory, lim.CPUs, lim.Pids)
	// The decoders' scratch is a bounded tmpfs, so a document that expands
	// without end fills that, not the host (runnerimage/decode writes only
	// a capped copy to /out). Archives unpack into a tmpfs of their own,
	// the size of the unpacked-bytes budget (D5), so the decoders keep
	// their scratch. Both count against the container's memory limit
	// beside Tika's heap; under a limit too low for all three the
	// container is killed and the decode fails, refusing the run.
	r.ReadOnly, r.Tmpfs = true, []string{"/tmp:size=512m,mode=1777", "/unpack:size=512m,mode=1777"}
	ctx, cancel := context.WithTimeout(ctx, Timeout)
	defer cancel()
	defer func() { _ = d.RemoveForce(context.WithoutCancel(ctx), name) }()
	var errOut bytes.Buffer
	code, err := d.RunForeground(ctx, r, nil, io.Discard, io.MultiWriter(stderr, &errOut))
	if err != nil {
		return nil, fmt.Errorf("the decode container: %w", err)
	}
	if code != 0 {
		return nil, fmt.Errorf("the decode container failed (exit %d): %s", code, strings.TrimSpace(tail(errOut.String(), 400)))
	}
	return Check(img, in, out)
}

// clamMount is where the decode container reads the signatures.
const clamMount = "/clamav"

// Check reads the report a decode wrote to out and holds it to what was
// staged under in (checkReport): Run's last step, and the one a caller
// that decodes some other way must take before it reads a byte of out.
func Check(img Image, in, out string) (*Result, error) {
	rep, err := checkReport(in, out, img.Signatures.Dir != "")
	if err != nil {
		return nil, err
	}
	return &Result{Report: rep, Image: img, In: in, Out: out}, nil
}

// checkReport reads the report the container wrote and holds it to what
// was staged. Everything under out was written by a process that read a
// hostile document, so it is read through an os.Root, regular files only,
// under a cap; and every entry must name a document that was staged, with
// its text, when there is one, at exactly <path>.txt. checked says the
// decode was given signatures: without them no file may claim to be checked.
func checkReport(in, out string, checked bool) (runnerdecode.Report, error) {
	var rep runnerdecode.Report
	inRoot, err := os.OpenRoot(in)
	if err != nil {
		return rep, err
	}
	defer func() { _ = inRoot.Close() }()
	outRoot, err := os.OpenRoot(out)
	if err != nil {
		return rep, err
	}
	defer func() { _ = outRoot.Close() }()
	raw, err := readRegular(outRoot, runnerdecode.ReportFile, maxReportBytes)
	if err != nil {
		return rep, fmt.Errorf("the decode wrote no readable %s: %w", runnerdecode.ReportFile, err)
	}
	if err := json.Unmarshal(raw, &rep); err != nil {
		return rep, fmt.Errorf("%s: %w", runnerdecode.ReportFile, err)
	}
	if rep.Schema != runnerdecode.Schema {
		return rep, fmt.Errorf("%s: schema %q is not %q", runnerdecode.ReportFile, rep.Schema, runnerdecode.Schema)
	}
	seen := map[string]bool{}
	byPath := map[string]runnerdecode.File{}
	for _, f := range rep.Files {
		if !relPath(f.Path) || byPath[f.Path].Path != "" {
			return rep, fmt.Errorf("%s names %q, which is not a document once", runnerdecode.ReportFile, f.Path)
		}
		// The family, the tool and the reason are words a run is shown
		// (list_inputs, the session's notice), so they are held to the
		// decode's own vocabulary: a decoder a document exploited could
		// otherwise put text of its choosing in front of the model
		// (agentry-cli#560).
		if !knownFamilies[f.Family] || !knownTools[f.Tool] || !knownWhy[f.Why] {
			return rep, fmt.Errorf("%s: %q has the unknown family %q, tool %q or reason %q", runnerdecode.ReportFile, f.Path, f.Family, f.Tool, f.Why)
		}
		if err := checkCheck(f, checked); err != nil {
			return rep, fmt.Errorf("%s: %w", runnerdecode.ReportFile, err)
		}
		byPath[f.Path] = f
	}
	members := 0
	for _, f := range rep.Files {
		if f.In != "" {
			if members++; members > runnerdecode.DefaultMaxFiles {
				return rep, fmt.Errorf("%s names more than %d archive members, past the decode's cap", runnerdecode.ReportFile, runnerdecode.DefaultMaxFiles)
			}
		}
		if err := checkFile(f, byPath, inRoot, outRoot); err != nil {
			return rep, fmt.Errorf("%s: %w", runnerdecode.ReportFile, err)
		}
		if f.In == "" {
			seen[f.Path] = true
		}
	}
	// A staged document the report leaves out is not decoded, and says so,
	// rather than vanishing from what a run is told it was given.
	err = fs.WalkDir(inRoot.FS(), ".", func(p string, e fs.DirEntry, err error) error {
		if err != nil || e.IsDir() || seen[p] {
			return err
		}
		rep.Files = append(rep.Files, runnerdecode.File{Path: p, Family: runnerdecode.FamilyUnknown, Outcome: runnerdecode.OutcomeUndecodable, Reason: notInReport})
		return nil
	})
	if err != nil {
		return rep, err
	}
	sort.Slice(rep.Files, func(i, j int) bool { return rep.Files[i].Path < rep.Files[j].Path })
	return rep, nil
}

// checkFile holds one report entry to what was staged: a file as staged
// is there, a regular file; a member names an archive the report says was
// unpacked, under that archive's path, no deeper than archives nest
// (plan file-handling.md §6, D5); and any text is at exactly <path>.txt,
// a regular file within the cap.
func checkFile(f runnerdecode.File, byPath map[string]runnerdecode.File, inRoot, outRoot *os.Root) error {
	if f.In == "" {
		fi, err := inRoot.Lstat(filepath.FromSlash(f.Path))
		if err != nil {
			return fmt.Errorf("it names %q, which was not staged: %w", f.Path, err)
		}
		if f.Outcome != runnerdecode.OutcomeRefused && !fi.Mode().IsRegular() {
			return fmt.Errorf("%q is not a regular file", f.Path)
		}
	} else if parent, ok := byPath[f.In]; !ok || parent.Outcome != runnerdecode.OutcomeUnpacked || !strings.HasPrefix(f.Path, f.In+"/") {
		return fmt.Errorf("%q names %q as its archive, which is not an archive the decode unpacked it from", f.Path, f.In)
	} else if !runnerdecode.PlainMemberPath(strings.TrimPrefix(f.Path, f.In+"/")) {
		// A member's path is shown to the model, and the container that
		// wrote it read the archive: it is held to the names the decode
		// itself accepts.
		return fmt.Errorf("%q is not a plain member path", f.Path)
	}
	switch f.Outcome {
	case runnerdecode.OutcomeRefused, runnerdecode.OutcomeUndecodable, runnerdecode.OutcomeText, runnerdecode.OutcomeDecoded:
		if f.Family == runnerdecode.FamilyArchive && (f.Outcome == runnerdecode.OutcomeText || f.Outcome == runnerdecode.OutcomeDecoded) {
			return fmt.Errorf("%q is an archive with the outcome %q", f.Path, f.Outcome)
		}
	case runnerdecode.OutcomeUnpacked:
		if f.Family != runnerdecode.FamilyArchive {
			return fmt.Errorf("%q was unpacked but is not an archive", f.Path)
		}
		if depth := archiveDepth(f, byPath); depth >= runnerdecode.MaxDepth {
			return fmt.Errorf("%q was unpacked inside %d archives, past the %d the decode unpacks", f.Path, depth, runnerdecode.MaxDepth)
		}
	default:
		return fmt.Errorf("%q has the unknown outcome %q", f.Path, f.Outcome)
	}
	if !f.HasText() {
		if f.Output != "" {
			return fmt.Errorf("%q has no text but names an output", f.Path)
		}
		return nil
	}
	if f.Output != f.Path+".txt" {
		return fmt.Errorf("it names an output outside the output root: %q is not %q", f.Output, f.Path+".txt")
	}
	ti, err := plainpath.File(outRoot, f.Output)
	if err != nil || ti.Size() > MaxTextBytes {
		return fmt.Errorf("the text of %q is not a regular file within %d bytes", f.Path, MaxTextBytes)
	}
	return nil
}

// checkCheck holds one entry's malware check to the closed vocabulary
// (plan file-handling.md §7): a known check and reason, a signature only
// on a finding and within ClamAV's grammar (it is shown to the person and,
// for a session's file, can reach the model), nothing checked when no
// signatures were given, every file read for the run checked one way or
// another, and a file found never read.
func checkCheck(f runnerdecode.File, checked bool) error {
	switch f.Check {
	case "":
		if f.HasText() || f.Outcome == runnerdecode.OutcomeText || f.Outcome == runnerdecode.OutcomeUnpacked {
			return fmt.Errorf("%q was read but the malware check says nothing of it", f.Path)
		}
	case runnerdecode.CheckClean, runnerdecode.CheckFound:
		if !checked {
			return fmt.Errorf("%q says ClamAV checked it, but the decode was given no signatures", f.Path)
		}
	case runnerdecode.CheckUnchecked:
	default:
		return fmt.Errorf("%q has the unknown check %q", f.Path, f.Check)
	}
	if (f.Check == runnerdecode.CheckUnchecked) != (f.Unchecked != "") || (f.Unchecked != "" && !knownUnchecked[f.Unchecked]) {
		return fmt.Errorf("%q has the check %q with the reason %q", f.Path, f.Check, f.Unchecked)
	}
	if !checked && f.Check == runnerdecode.CheckUnchecked && f.Unchecked != runnerdecode.UncheckedNoSignatures {
		return fmt.Errorf("%q says ClamAV failed on it, but the decode was given no signatures", f.Path)
	}
	if f.Signature != "" && (f.Check != runnerdecode.CheckFound || !runnerdecode.ValidSignature(f.Signature)) {
		return fmt.Errorf("%q names the signature %q", f.Path, f.Signature)
	}
	if (f.Why == runnerdecode.WhyFound) != (f.Check == runnerdecode.CheckFound && f.Family != runnerdecode.FamilyArchive) {
		return fmt.Errorf("%q has the check %q and the reason %q", f.Path, f.Check, f.Why)
	}
	if f.Why == runnerdecode.WhyFound && (f.Outcome != runnerdecode.OutcomeRefused || f.Output != "") {
		return fmt.Errorf("%q was found by ClamAV but read", f.Path)
	}
	return nil
}

// archiveDepth is how many archives enclose f. Each In is a strict prefix
// of its member's path, so the chain ends.
func archiveDepth(f runnerdecode.File, byPath map[string]runnerdecode.File) int {
	n := 0
	for f.In != "" {
		n++
		f = byPath[f.In]
	}
	return n
}

// The decode's vocabulary: every family, tool and reason a report may
// name.
var (
	knownFamilies = map[runnerdecode.Family]bool{
		runnerdecode.FamilyText: true, runnerdecode.FamilyPDF: true, runnerdecode.FamilyDocument: true,
		runnerdecode.FamilyPresentation: true, runnerdecode.FamilySpreadsheet: true,
		runnerdecode.FamilyImage: true, runnerdecode.FamilyArchive: true, runnerdecode.FamilyUnknown: true,
	}
	knownTools = map[string]bool{"": true, "pdftotext": true, "pandoc": true, "tesseract": true, "agentry-runner": true, "tika": true, "bsdtar": true, "bsdcat": true}
	// whyWords are the fixed words for each reason an archive or a member
	// was not read in full.
	whyWords = map[runnerdecode.Why]string{
		runnerdecode.WhyEncrypted:  "encrypted",
		runnerdecode.WhyDamaged:    "damaged, or not the archive it appears to be",
		runnerdecode.WhyUnreadable: "bsdtar could not read it: it is encrypted or damaged",
		runnerdecode.WhyTooDeep:    fmt.Sprintf("an archive nested more than %d deep is not unpacked", runnerdecode.MaxDepth),
		runnerdecode.WhyTooMany:    "unpacking stopped at the file cap",
		runnerdecode.WhyTooLarge:   "unpacking stopped at the cap on unpacked bytes",
		runnerdecode.WhyUnsafePath: "a member's path is absolute, climbs out with .., or is not a plain name, so nothing in it was unpacked",
		runnerdecode.WhyLink:       "a link in an archive is never unpacked",
		runnerdecode.WhySpecial:    "a device or FIFO in an archive is never unpacked",
		runnerdecode.WhyConflict:   "the archive names this path twice, or as both a file and a folder",
		runnerdecode.WhyMethod:     "compressed by a method the runner does not read",
		runnerdecode.WhyFound:      "ClamAV found malware in it, so it was not read",
	}
	knownUnchecked = map[runnerdecode.Unchecked]bool{
		runnerdecode.UncheckedNoSignatures: true, runnerdecode.UncheckedTooLarge: true, runnerdecode.UncheckedFailed: true,
	}
	knownWhy = func() map[runnerdecode.Why]bool {
		m := map[runnerdecode.Why]bool{"": true}
		for w := range whyWords {
			m[w] = true
		}
		return m
	}()
)

// notInReport is the reason the host gives a staged file the decode's
// report left out: the host's own words, so passed on as they are.
const notInReport = "the decode's report does not name it"

// UnreadReason is why a file was not read, in fixed words chosen by its
// outcome and tool. The report's own reason is never passed on: it can
// carry a decoder's error output, which can quote the document, and a run
// shows the reason to the model (list_inputs, read_input, a session's
// notice; agentry-cli#560).
func UnreadReason(f runnerdecode.File) string {
	switch {
	case f.Reason == notInReport:
		return notInReport
	case f.Why != "":
		return whyWords[f.Why]
	case f.Outcome == runnerdecode.OutcomeRefused:
		return "refused: not a regular file, or past the file cap"
	case f.Tool != "":
		return f.Tool + " could not read it"
	case f.Family == runnerdecode.FamilyUnknown:
		return "not text, and no decoder reads this kind of file"
	}
	return "it could not be decoded"
}

// UnpackedInPart is why an archive that was unpacked was unpacked only in
// part, in the decode's fixed words, or "" when it was unpacked whole.
func UnpackedInPart(f runnerdecode.File) string {
	if f.Outcome != runnerdecode.OutcomeUnpacked || f.Why == "" {
		return ""
	}
	return whyWords[f.Why]
}

func relPath(p string) bool {
	return p != "" && !path.IsAbs(p) && path.Clean(p) == p && p != ".." && !strings.HasPrefix(p, "../") && !strings.Contains(p, "\\")
}

// readRegular reads a regular file under root, refusing a link, a device
// or more than limit bytes.
func readRegular(root *os.Root, name string, limit int64) ([]byte, error) {
	if _, err := plainpath.File(root, filepath.ToSlash(name)); err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	f, err := root.Open(name)
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	b, err := io.ReadAll(io.LimitReader(f, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(b)) > limit {
		return nil, fmt.Errorf("%s is larger than %d bytes", name, limit)
	}
	return b, nil
}

// Decoded counts the files that were decoded into text.
func (r *Result) Decoded() int { return r.count(runnerdecode.OutcomeDecoded) }

// Text counts the files read as they are.
func (r *Result) Text() int { return r.count(runnerdecode.OutcomeText) }

// Undecodable names the files neither decoded nor read as text: those no
// decoder reads, those a decoder failed on, and those refused.
func (r *Result) Undecodable() []string {
	var out []string
	for _, f := range r.Report.Files {
		if f.Outcome == runnerdecode.OutcomeUndecodable || f.Outcome == runnerdecode.OutcomeRefused {
			out = append(out, f.Path)
		}
	}
	return out
}

func (r *Result) count(outcome runnerdecode.Outcome) int {
	n := 0
	for _, f := range r.Report.Files {
		if f.Outcome == outcome {
			n++
		}
	}
	return n
}

// Line is the receipt's decode line: the mechanism, the versions, and what
// happened to the files.
func (r *Result) Line() string {
	return r.LineAs("the inputs were decoded before the run")
}

// LineAs is Line led by its own account of when the decode happened: a
// session's files added mid-run were decoded before the agent was told of
// them, not before the run (agentry-cli#560).
func (r *Result) LineAs(when string) string {
	pkgs := append([]string(nil), r.Image.Packages...)
	sort.Strings(pkgs)
	commands := make([]string, 0, len(Catalogue))
	for _, t := range Catalogue {
		commands = append(commands, t.Command)
	}
	sort.Strings(commands)
	return when + ", in " + r.Image.Tag + " (built on " + r.Image.Files + ")" +
		" with no network, every capability dropped and the inputs read-only," +
		" by " + andList(commands) + " (" + strings.Join(pkgs, ", ") + ")" +
		" and the runner's own spreadsheet, slide, zip and tar readers: " + r.Counts() +
		"; " + r.Checks()
}

// Found is every file ClamAV found a signature in: the run is refused
// before the agent starts (plan file-handling.md D9).
func (r *Result) Found() []runnerdecode.File {
	var out []runnerdecode.File
	for _, f := range r.Report.Files {
		if f.Check == runnerdecode.CheckFound {
			out = append(out, f)
		}
	}
	return out
}

// Refusal is the sentence a refused run, or a session's refused file,
// gives: each file found and its signature, in the decode's own words.
func (r *Result) Refusal() string {
	found := r.Found()
	parts := make([]string, 0, len(found))
	for i, f := range found {
		if i == 5 {
			parts = append(parts, fmt.Sprintf("and %d more", len(found)-5))
			break
		}
		sig := f.Signature
		if sig == "" {
			sig = "a signature"
		}
		parts = append(parts, f.Path+" ("+sig+")")
	}
	return "ClamAV found malware in " + strings.Join(parts, ", ")
}

// Checks is the malware check's clause of the receipt: the signatures'
// date and bundle, what was clean, found and not checked, and whether the
// signatures were stale or could not be refreshed (plan §3 invariant 7).
func (r *Result) Checks() string {
	s := r.Image.Signatures
	clean, found := 0, 0
	unchecked := map[runnerdecode.Unchecked]int{}
	for _, f := range r.Report.Files {
		switch f.Check {
		case runnerdecode.CheckClean:
			clean++
		case runnerdecode.CheckFound:
			found++
		case runnerdecode.CheckUnchecked:
			unchecked[f.Unchecked]++
		}
	}
	if s.Dir == "" {
		problem := s.Problem
		if problem == "" {
			problem = clamdb.ProblemNone
		}
		return "no file was checked for malware: " + problem
	}
	digest := strings.TrimPrefix(s.Digest, "sha256:")
	if len(digest) > 12 {
		digest = digest[:12]
	}
	line := fmt.Sprintf("each file and archive member was checked by ClamAV (clamscan, PUA off) before any decoder read it, against the signatures of %s (daily %d, main %d; %s@sha256:%s): %d clean",
		s.Daily.Built.UTC().Format("2006-01-02 15:04 UTC"), s.Daily.Number, s.Main.Number, s.Ref, digest, clean)
	if found > 0 {
		line += fmt.Sprintf(", %d found", found)
	}
	for _, u := range []runnerdecode.Unchecked{runnerdecode.UncheckedTooLarge, runnerdecode.UncheckedFailed} {
		if n := unchecked[u]; n > 0 {
			line += fmt.Sprintf(", %d not checked (%s)", n, uncheckedWords[u])
		}
	}
	if s.Stale {
		line += fmt.Sprintf("; the signatures are stale, more than %d days old", int(clamdb.StaleAfter.Hours()/24))
	}
	if s.Problem != "" {
		line += "; " + s.Problem
	}
	return line
}

// uncheckedWords are the receipt's words for why a file was not checked.
var uncheckedWords = map[runnerdecode.Unchecked]string{
	runnerdecode.UncheckedTooLarge: "past ClamAV's limits",
	runnerdecode.UncheckedFailed:   "ClamAV could not read it",
}

// Counts is what happened to the files: how many were decoded, read as
// text, and not decoded, naming the first few of those.
func (r *Result) Counts() string {
	line := fmt.Sprintf("%d decoded, %d read as text", r.Decoded(), r.Text())
	if n := r.count(runnerdecode.OutcomeUnpacked); n > 0 {
		line += fmt.Sprintf(", %d %s unpacked", n, plural(n, "archive", "archives"))
		partial := 0
		for _, f := range r.Report.Files {
			if UnpackedInPart(f) != "" {
				partial++
			}
		}
		if partial > 0 {
			line += fmt.Sprintf(" (%d in part)", partial)
		}
	}
	if bad := r.Undecodable(); len(bad) > 0 {
		shown := bad
		if len(shown) > 5 {
			shown = shown[:5]
		}
		line += fmt.Sprintf(", %d not decoded (%s", len(bad), strings.Join(shown, ", "))
		if len(bad) > len(shown) {
			line += fmt.Sprintf(" and %d more", len(bad)-len(shown))
		}
		line += ")"
	}
	return line
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}

// andList is "a", "a and b", "a, b and c".
func andList(items []string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	}
	return strings.Join(items[:len(items)-1], ", ") + " and " + items[len(items)-1]
}

func invokingUser() string {
	uid, gid := os.Getuid(), os.Getgid()
	if uid < 0 || gid < 0 {
		return ""
	}
	return fmt.Sprintf("%d:%d", uid, gid)
}

func tail(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[len(s)-n:]
}
