// TestTheCfgFolderIsHeldToTheCatalogsEntries: beneath the run's cfg
// folder the filter admits only what the catalog binds there, each path to
// the entries that bind it: never cfg itself, the harness's files, the
// model sign-in's token or the gateway's secrets file, and never a
// connection's token, the hosts' sign-ins, the browser's secrets or the
// share's verdicts to another container.
func TestTheCfgFolderIsHeldToTheCatalogsEntries(t *testing.T) {
	const run, cfg = "/r/run", "/r/run/cfg"
	catalog := strings.NewReplacer("CFG", cfg, "RUN", run).Replace(heldCatalog)
	roots, writable, held, err := cfgBinds([]string{run + "/workspace", cfg, run + "/out"},
		[]string{run + "/out", cfg + "/hostfiles", cfg + "/connections/gone", cfg}, cfg, []byte(catalog))
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(writable, []string{run + "/out", cfg + "/hostfiles"}) {
		t.Errorf("writable %v: a writable path beneath cfg the catalog does not bind is kept", writable)
	}
	if slices.Contains(roots, cfg) || !slices.Contains(roots, run+"/workspace") || !slices.Contains(roots, run+"/out") {
		t.Fatalf("roots %v", roots)
	}
	tools := sockfilter.Holder{Image: "agentry-runner:test", Cmd: []string{"tools", "--spec", "/etc/agentry/toolspec.json"}}
	bridge := sockfilter.Holder{Image: "agentry-runner:test", Cmd: []string{"bridge", "--url", "https://mcp.example.org/mcp", "--token-file", "/run/agentry/connection/bearer"}}
	browser := sockfilter.Holder{Image: "agentry-browser:test", Cmd: []string{"browse", "--proxy", "proxy-1:3128"}}
	hosts := sockfilter.Holder{Image: "agentry-hostlink:test", Cmd: []string{"hostlink"}}
	signedIn := sockfilter.Holder{Image: "python:3.13-slim", Cmd: []string{"/opt/agentry-mcp/y/venv/bin/workspace_mcp"}}
	want := map[string][]sockfilter.Holder{
		cfg + "/gateway/toolspec.json":  {tools},
		cfg + "/share-checks":           {tools},
		cfg + "/browserout":             {tools, browser},
		cfg + "/hostfiles":              {tools, hosts},
		cfg + "/connections/mcp-remote": {bridge},
		cfg + "/gateway/browser.json":   {browser},
		cfg + "/browser/secrets.env":    {browser},
		cfg + "/gateway/hostspec.json":  {hosts},
		cfg + "/hosts":                  {hosts},
		cfg + "/hosts/passwd":           {hosts},
		cfg + "/hostlog":                {hosts},

		cfg + "/connections/mcp-pypi-workspace-mcp": {signedIn},
	}
	if len(held) != len(want) {
		t.Fatalf("held %d paths, want %d: %v", len(held), len(want), held)
	}
	for _, h := range held {
		w, ok := want[h.Root]
		if !ok || len(h.By) != len(w) {
			t.Errorf("%s held to %v, want %v", h.Root, h.By, w)
			continue
		}
		for _, by := range w {
			if !slices.ContainsFunc(h.By, func(o sockfilter.Holder) bool { return o.Image == by.Image && slices.Equal(o.Cmd, by.Cmd) }) {
				t.Errorf("%s held to %v, want %v among them", h.Root, h.By, by)
			}
		}
		if !slices.Contains(roots, h.Root) {
			t.Errorf("held path %s is not a root %v", h.Root, roots)
		}
	}
	// A holder is given exactly the folders its entry binds, the code
	// outside cfg included, and the options left out.
	for _, c := range []struct {
		root  string
		image string
		binds []sockfilter.HolderBind
	}{
		{cfg + "/connections/mcp-pypi-workspace-mcp", "python:3.13-slim", []sockfilter.HolderBind{
			{Source: run + "/servers/y", Target: "/opt/agentry-mcp/y"},
			{Source: cfg + "/connections/mcp-pypi-workspace-mcp", Target: "/run/agentry/connection"},
		}},
		{cfg + "/connections/mcp-remote", "agentry-runner:test", []sockfilter.HolderBind{
			{Source: cfg + "/connections/mcp-remote", Target: "/run/agentry/connection"},
		}},
		{cfg + "/hostlog", "agentry-hostlink:test", []sockfilter.HolderBind{
			{Source: cfg + "/gateway/hostspec.json", Target: "/etc/agentry/hostspec.json"},
			{Source: cfg + "/hosts", Target: "/run/agentry/hosts"},
			{Source: cfg + "/hosts/passwd", Target: "/etc/passwd"},
			{Source: cfg + "/hostlog", Target: "/run/agentry/hostlog"},
			{Source: cfg + "/hostfiles", Target: "/run/agentry/hostfiles"},
		}},
	} {
		i := slices.IndexFunc(held, func(h sockfilter.HeldRoot) bool { return h.Root == c.root })
		if i < 0 {
			t.Errorf("%s is not held", c.root)
			continue
		}
		if by := held[i].By; len(by) != 1 || by[0].Image != c.image || !slices.Equal(by[0].Binds, c.binds) {
			t.Errorf("%s is held to %+v, want the binds %v", c.root, by, c.binds)
		}
	}
	for _, p := range []string{cfg, cfg + "/harness", cfg + "/model-signin", cfg + "/gateway", cfg + "/gateway/secrets.env", cfg + "/connections"} {
		for _, r := range roots {
			if p == r || strings.HasPrefix(p, r+"/") {
				t.Errorf("%s is admitted by root %s", p, r)
			}
		}
	}
	// A folder that only starts like cfg is not beneath it: it is neither held
	// nor dropped from the writable paths. And with no cfg folder at all the
	// lists pass through as they came.
	sibling := []byte("registry:\n  e:\n    image: i\n    command: [c]\n    volumes:\n      - '" + cfg + "2/y:/y:ro'\n")
	roots2, writable2, held2, err := cfgBinds([]string{run + "/workspace", cfg + "2"}, []string{cfg + "2/z"}, cfg, sibling)
	if err != nil || len(held2) != 0 || !slices.Equal(roots2, []string{run + "/workspace", cfg + "2"}) || !slices.Equal(writable2, []string{cfg + "2/z"}) {
		t.Errorf("a sibling of cfg: roots %v, writable %v, held %v, %v", roots2, writable2, held2, err)
	}
	// Entries that bind one path are told apart by image, command and binds
	// alike; one that repeats another's is listed once; a bind of cfg itself
	// is held like any other.
	same := []byte(`registry:
  e1: {image: i, command: [a], volumes: ['` + cfg + `/p:/x']}
  e2: {image: i, command: [a], volumes: ['` + cfg + `/p:/x']}
  e3: {image: i, command: [b], volumes: ['` + cfg + `/p:/x']}
  e4: {image: i, command: [a], volumes: ['` + cfg + `/p:/x', '` + cfg + `/q:/y']}
  e5: {image: j, command: [a], volumes: ['` + cfg + `:/whole']}
`)
	_, _, held2, err = cfgBinds(nil, nil, cfg, same)
	if err != nil {
		t.Fatal(err)
	}
	count := map[string]int{}
	for _, h := range held2 {
		count[h.Root] = len(h.By)
	}
	if len(held2) != 3 || count[cfg+"/p"] != 3 || count[cfg+"/q"] != 1 || count[cfg] != 1 {
		t.Errorf("holders per path %v, want 3 for p (e1 and e2 are one), 1 for q, 1 for cfg itself", count)
	}
	roots2, writable2, held2, err = cfgBinds([]string{".", cfg, run + "/out"}, []string{".", cfg + "/x"}, "", []byte(catalog))
	if err != nil || len(held2) != 0 || !slices.Equal(roots2, []string{".", cfg, run + "/out"}) || !slices.Equal(writable2, []string{".", cfg + "/x"}) {
		t.Errorf("no cfg folder: roots %v, writable %v, held %v, %v", roots2, writable2, held2, err)
	}
	if _, _, _, err := cfgBinds([]string{cfg}, nil, cfg, []byte("registry: [not, a, mapping]")); err == nil || !strings.Contains(err.Error(), "read the gateway's catalog") {
		t.Errorf("a catalog that is not a mapping: %v", err)
	}
	// No catalog: nothing beneath cfg.
	roots, _, held, err = cfgBinds([]string{cfg, run + "/out"}, nil, cfg, nil)
	if err != nil || len(held) != 0 || !slices.Equal(roots, []string{run + "/out"}) {
		t.Errorf("no catalog: roots %v, held %v, %v", roots, held, err)
	}
}

// TestFilterHoldsTheRunsCfgFolder: the run's filter takes the cfg folder's
// paths and holders from the catalog the run rendered for its gateway.
func TestFilterHoldsTheRunsCfgFolder(t *testing.T) {
	rd := runDirsAt(t.TempDir())
	if err := os.MkdirAll(filepath.Join(rd.cfg, "gateway"), 0o755); err != nil {
		t.Fatal(err)
	}
	catalog := strings.NewReplacer("CFG", rd.gatewayPath(rd.cfg), "RUN", rd.gatewayPath(rd.root)).Replace(heldCatalog)
	if err := os.WriteFile(filepath.Join(rd.cfg, "gateway", "catalog.yaml"), []byte(catalog), 0o644); err != nil {
		t.Fatal(err)
	}
	env := map[string]string{"MCP_GATEWAY_DOCKER_BIND_ALLOWED_PATHS": rd.workspace + ":" + rd.cfg}
	cfg, err := filterConfig(rd, "run1", env, policy.Limits{}, &spec.Plan{}, nil)
	if err != nil {
		t.Fatal(err)
	}
	checks := rd.gatewayPath(filepath.Join(rd.cfg, "share-checks"))
	if slices.Contains(cfg.BindRoots, rd.gatewayPath(rd.cfg)) || !slices.Contains(cfg.BindRoots, checks) {
		t.Errorf("roots %v", cfg.BindRoots)
	}
	i := slices.IndexFunc(cfg.HeldRoots, func(h sockfilter.HeldRoot) bool { return h.Root == checks })
	if i < 0 || len(cfg.HeldRoots[i].By) != 1 || cfg.HeldRoots[i].By[0].Cmd[0] != "tools" {
		t.Errorf("the share's verdicts are held to %v", cfg.HeldRoots)
	}
	if len(cfg.HeldVolumes) != 0 {
		t.Errorf("a plan with no image server holds volumes %v", cfg.HeldVolumes)
	}

	// An image server's volume is held to the catalog entries that mount it:
	// none here, so no container may mount it.
	image := &spec.Plan{MCPServers: []spec.MCPServerSpec{{Name: "mcp-image-gog", Source: spec.SourceImage, Image: "ghcr.io/example/gog:1", Volumes: []string{"agentry-persistent-gog:/persist/gogcli"}}}}
	cfg, err = filterConfig(rd, "run1", env, policy.Limits{}, image, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(cfg.HeldVolumes) != 1 || cfg.HeldVolumes[0].Root != "agentry-persistent-gog" || len(cfg.HeldVolumes[0].By) != 0 {
		t.Errorf("an image server's volume is held to %+v", cfg.HeldVolumes)
	}

	// A catalog that cannot be read, not one that is absent, stops the run.
	unreadable := runDirsAt(t.TempDir())
	if err := os.MkdirAll(filepath.Join(unreadable.cfg, "gateway", "catalog.yaml"), 0o755); err != nil {
		t.Fatal(err)
	}
	var ce *ClassifiedError
	if _, err := filterConfig(unreadable, "run1", nil, policy.Limits{}, &spec.Plan{}, nil); !errors.As(err, &ce) || ce.Code != ExitGateway || !strings.Contains(err.Error(), "read the gateway's catalog") {
		t.Errorf("a catalog that cannot be read: %v", err)
	}
	if _, err := filterConfig(runDirsAt(t.TempDir()), "run1", nil, policy.Limits{}, &spec.Plan{}, nil); err != nil {
		t.Errorf("a run with no catalog yet: %v", err)
	}
}

// TestAnImageServersVolumeIsHeldToTheEntryThatMountsIt: the docker filter
// holds an image server's volume to the catalog entries that mount it, by
// image, command and exactly their binds, and a volume no entry mounts to
// none.
func TestAnImageServersVolumeIsHeldToTheEntryThatMountsIt(t *testing.T) {
	catalog := []byte(`registry:
  mcp-image-gog:
    image: ghcr.io/example/gog:1
    command: [mcp, --allow-write]
    volumes:
      - agentry-persistent-assistant-0123456789-gog:/persist/gogcli
  agentry-tools:
    image: agentry-runner:test
    command: [tools]
    volumes:
      - /run/cfg/toolspec.json:/etc/agentry/toolspec.json:ro
`)
	// No volume to hold: the catalog is not even read.
	if none, err := volumeHolders([]byte("registry: [not, a, mapping]"), nil); none != nil || err != nil {
		t.Fatalf("no volumes: %v %v", none, err)
	}
	held, err := volumeHolders(catalog, []string{"agentry-persistent-assistant-0123456789-gog", "agentry-persistent-assistant-0123456789-unmounted"})
	if err != nil {
		t.Fatal(err)
	}
	if len(held) != 2 {
		t.Fatalf("held = %+v", held)
	}
	gog := held[0]
	if gog.Root != "agentry-persistent-assistant-0123456789-gog" || len(gog.By) != 1 || gog.By[0].Image != "ghcr.io/example/gog:1" ||
		!slices.Equal(gog.By[0].Cmd, []string{"mcp", "--allow-write"}) || len(gog.By[0].Binds) != 1 || gog.By[0].Binds[0].Target != "/persist/gogcli" {
		t.Fatalf("the gog volume's holders: %+v", gog)
	}
	if none := held[1]; len(none.By) != 0 {
		t.Fatalf("an unmounted volume is held to %+v", none.By)
	}
}
