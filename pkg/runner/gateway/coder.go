// CoderRecordFile is where the Coding agent's toolchain image records each
// tool's version and the Debian snapshot it was built from, read back into
// the receipt.
const CoderRecordFile = "/etc/agentry/coder/record"

// ensureCoderExecImage builds the Coding agent's exec image when absent: its
// toolchain image, pinned by digest, with the runner binary, the PDF
// renderer and ripgrep copied in and the runner as the entrypoint the tools
// server is started through. Nothing is installed or minimized. It returns
// the toolchain's record, one "tool version" a line.
func ensureCoderExecImage(ctx context.Context, d dockerx.Client, runnerImage string, img spec.ExecImageSpec, ctxDir string, logw io.Writer) ([]string, error) {
	if !policy.PinnedByDigest(img.Coder) {
		return nil, fmt.Errorf("the plan's Coding agent toolchain image %q is not pinned by digest", img.Coder)
	}
	ok, err := d.ImageExists(ctx, img.Tag)
	if err != nil {
		return nil, err
	}
	if !ok {
		dir := filepath.Join(ctxDir, "exec-"+img.Tag[strings.LastIndex(img.Tag, ":")+1:])
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return nil, fmt.Errorf("the Coding agent's exec image context: %w", err)
		}
		if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(coderDockerfile(runnerImage, img)), 0o600); err != nil {
			return nil, fmt.Errorf("the Coding agent's exec image context: %w", err)
		}
		_, _ = fmt.Fprintf(logw, "building %s (the Coding agent's toolchain %s with the runner binary, not minimized)\n", img.Tag, img.Coder)
		if err := d.Build(ctx, dir, img.Tag, nil); err != nil {
			return nil, fmt.Errorf("build the Coding agent's exec image %s: %w", img.Tag, err)
		}
	}
	b, err := d.ImageFile(ctx, img.Tag, CoderRecordFile)
	if err != nil {
		return nil, fmt.Errorf("read the Coding agent's toolchain record: %w", err)
	}
	var out []string
	for _, line := range strings.Split(string(b), "\n") {
		if line = strings.TrimSpace(line); line != "" {
			out = append(out, line)
		}
	}
	return out, nil
}

// coderDockerfile renders the build. The toolchain image runs as its own
// user; the tools server runs as root, as in every exec image, and starts
// each program as the person's ids (toolsrv.Exec.Any).
func coderDockerfile(runnerImage string, img spec.ExecImageSpec) string {
	var b strings.Builder
	b.WriteString("# generated by agentry: the Coding agent's toolchain image with the runner binary; not minimized, and no command is declared\n")
	b.WriteString("FROM " + img.Coder + "\n")
	b.WriteString(imagelabel.Line(imagelabel.CoderExec))
	b.WriteString("COPY --from=" + runnerImage + " /usr/local/bin/agentry-runner /usr/local/bin/agentry-runner\n")
	b.WriteString("COPY --from=" + runnerImage + " " + toolsrv.TypstDir + " " + toolsrv.TypstDir + "\n")
	b.WriteString("COPY --from=" + runnerImage + " " + toolsrv.RipgrepDir + " " + toolsrv.RipgrepDir + "\n")
	b.WriteString("USER 0:0\n")
	b.WriteString("ENTRYPOINT [\"/usr/local/bin/agentry-runner\"]\n")
	return b.String()
}
