// The host link's image (plan runtime-hosts.md D5; DR-91): the hostlink
// image, pinned by digest and pulled, with this CLI's runner binary copied
// in, built the way the decode image is (agentry-cli#559). The build
// installs nothing. It is minimized to ssh and sftp, so the client's other
// programs (scp, ssh-agent, ssh-add, ssh-keyscan, the shell) are not there
// for anything to run, and the runner answers as SSH_ASKPASS through a link
// made before the minimize step, while the image still has a shell's ln.

// HostlinkPackagesFile is where the hostlink image records the version apk
// resolved for each of its packages.
const HostlinkPackagesFile = "/etc/agentry/hostlink/packages"

// hostlinkUser is the image's own user (DR-91), restored after the build.
const hostlinkUser = "10001:10001"

// hostLinkPrograms are the programs the minimized image keeps.
var hostLinkPrograms = []string{"ssh", "sftp", filepath.Base(hostlink.AskpassProgram)}

// ImageSpec is the host link's image for a runner image and a base.
type ImageSpec struct {
	Tag, Base, Runner string
}

// HostLinkImage is the image spec; its tag is a hash of the whole build,
// so a new runner, base or recipe gets an image of its own.
func HostLinkImage(runnerImage, base string) ImageSpec {
	s := ImageSpec{Base: base, Runner: runnerImage}
	sum := sha256.Sum256([]byte(s.Dockerfile()))
	s.Tag = "agentry-hostlink-local:" + hex.EncodeToString(sum[:])[:16]
	return s
}

// Dockerfile is the build, every step in exec form.
func (s ImageSpec) Dockerfile() string {
	quoted := make([]string, 0, len(hostLinkPrograms))
	for _, k := range hostLinkPrograms {
		quoted = append(quoted, fmt.Sprintf("%q", k))
	}
	sort.Strings(quoted)
	return "# generated by agentry: the host link's image, the hostlink image pinned by digest with this CLI's runner binary, minimized to ssh and sftp (agentry-cli#861)\n" +
		"FROM " + s.Base + "\n" +
		"USER 0:0\n" +
		"COPY --from=" + s.Runner + " /usr/local/bin/agentry-runner /usr/local/bin/agentry-runner\n" +
		"RUN [\"/bin/ln\", \"-s\", \"agentry-runner\", \"" + hostlink.AskpassProgram + "\"]\n" +
		"RUN [\"/usr/local/bin/agentry-runner\", \"minimize\", " + strings.Join(quoted, ", ") + "]\n" +
		"USER " + hostlinkUser + "\n" +
		"ENTRYPOINT [\"/usr/local/bin/agentry-runner\"]\n"
}

// Image is a built host link image and the packages its base recorded.
type Image struct {
	Tag, Base string
	Packages  []string
}

var (
	pullAttempts = 3
	pullBackoff  = 5 * time.Second
)

// BaseRef is the base the policy names, refused unless pinned by digest.
func BaseRef(pol *policy.Policy) (string, error) {
	ref := pol.Images.HostlinkImage()
	if !policy.PinnedByDigest(ref) {
		return "", fmt.Errorf("the hostlink image %q is not pinned by digest; images.hostlink must be <name>@sha256:<digest>", ref)
	}
	return ref, nil
}

// EnsureImage builds the host link's image when it is missing, pulling the
// base by digest first, and reads back the package versions it recorded.
func EnsureImage(ctx context.Context, d dockerx.Client, s ImageSpec, ctxDir string, logw io.Writer) (Image, error) {
	if !policy.PinnedByDigest(s.Base) {
		return Image{}, fmt.Errorf("the hostlink image %q is not pinned by digest", s.Base)
	}
	ok, err := d.ImageExists(ctx, s.Tag)
	if err != nil {
		return Image{}, err
	}
	if !ok {
		if err := pullBase(ctx, d, s.Base, logw); err != nil {
			return Image{}, err
		}
		dir := filepath.Join(ctxDir, "hostlink-"+s.Tag[strings.LastIndex(s.Tag, ":")+1:])
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return Image{}, fmt.Errorf("the host link image's context: %w", err)
		}
		if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(s.Dockerfile()), 0o600); err != nil {
			return Image{}, fmt.Errorf("the host link image's context: %w", err)
		}
		_, _ = fmt.Fprintf(logw, "building %s (the hostlink image %s with this CLI's runner, minimized to ssh and sftp; nothing is installed)\n", s.Tag, s.Base)
		if err := d.Build(ctx, dir, s.Tag, nil); err != nil {
			return Image{}, fmt.Errorf("build the host link image %s on %s: %w", s.Tag, s.Base, err)
		}
	}
	b, err := d.ImageFile(ctx, s.Tag, HostlinkPackagesFile)
	if err != nil {
		return Image{}, fmt.Errorf("read the hostlink image's package record: %w", err)
	}
	var pkgs []string
	for _, line := range strings.Split(string(b), "\n") {
		if line = strings.TrimSpace(line); line != "" {
			pkgs = append(pkgs, line)
		}
	}
	sort.Strings(pkgs)
	return Image{Tag: s.Tag, Base: s.Base, Packages: pkgs}, nil
}

func pullBase(ctx context.Context, d dockerx.Client, ref string, logw io.Writer) error {
	ok, err := d.ImageExists(ctx, ref)
	if err != nil || ok {
		return err
	}
	_, _ = fmt.Fprintf(logw, "pulling the hostlink image %s (once on this machine)\n", ref)
	var last error
	for i := 1; i <= pullAttempts; i++ {
		if last = d.Pull(ctx, ref); last == nil {
			return nil
		}
		if i < pullAttempts {
			_, _ = fmt.Fprintf(logw, "pull failed (%v); trying again\n", last)
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(pullBackoff * time.Duration(i)):
			}
		}
	}
	return fmt.Errorf("could not pull the hostlink image %s, which the run reaches its target hosts with, after %d attempts: %w", ref, pullAttempts, last)
}
